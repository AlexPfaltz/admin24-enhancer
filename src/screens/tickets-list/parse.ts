/**
 * Регулярка для разбора заголовка заявки вида:
 *   11972: Заявка с формы [ Задачи ИТ ] РАЗРАБОТКА И ПРИКЛАДНЫЕ СЕРВИСЫ
 *   12020: Заявка с формы [ Дентал-Сервис ] Не работает внп
 *   11965: ИНФРАСТРУКТУРНЫЕ СЕРВИСЫ
 *
 * Группы:
 *   1 — id (число)
 *   2 — форма (внутри [ ... ])
 *   3 — чистый заголовок (всё после ] или всё после "id:")
 *
 * Префикс «Заявка с формы» — опциональный.
 */
const TITLE_RE =
  /^(\d+)\s*:\s*(?:Заявка с формы\s*)?\[\s*([^\]]+?)\s*\]\s*(.*)$/;

/**
 * Возвращает «чистое» название заявки без служебного префикса
 * «Заявка с формы [ Форма ]». Если паттерн не совпал — возвращает
 * оригинальный текст без изменений.
 */
export function simplifyTitle(original: string): string {
  const trimmed = original.trim();
  const match = TITLE_RE.exec(trimmed);
  if (!match) return original;

  const cleaned = match[3]?.trim() ?? "";
  // Если после префикса ничего не осталось — не упрощаем, чтобы не
  // получить пустую строку вместо заголовка.
  if (!cleaned) return original;

  return cleaned;
}